/**
 * Maps Supabase Phieu_kho row to internal StockSlip interface
 * Supports both Vietnamese (ma_phieu, loai_phieu, ...) and English (code, type, ...) schemas
 */
export function mapRowToStockSlip(row: any): StockSlip {
  const rawType = row.loai_phieu || row.Loai_phieu || row.type || row.Type || 'Nhập kho';
  const type: 'Nhập kho' | 'Xuất kho' | 'Chuyển kho' =
    rawType === 'Xuất kho' || rawType === 'Chuyển kho' ? rawType : 'Nhập kho';

  const rawCreator = (row.nguoi_tao || row.Nguoi_tao || row.creator || row.Creator || '')
    .replace(/\s*\([^)]*\)/g, '')
    .trim();
  const creator =
    rawCreator === 'Lê Văn Hải' || rawCreator === 'Nguyễn Hữu Hòa'
      ? rawCreator
      : 'Nguyễn Hữu Hòa';

  const rawDeliverer = row.nguoi_giao || row.deliverer || row.kho_nguon || row.warehouseSource || '';
  const deliverer =
    rawDeliverer === 'Trần Quang Hiếu' || rawDeliverer === 'Ngô Thiện Nhân'
      ? rawDeliverer
      : 'Ngô Thiện Nhân';

  const rawReceiver = row.nguoi_nhan || row.receiver || '';
  const receiver =
    rawReceiver === 'Lê Ngọc Nhàn' ||
    rawReceiver === 'Bùi Văn Thuận' ||
    rawReceiver === 'Thái Ngọc Thức'
      ? rawReceiver
      : 'Lê Ngọc Nhàn';

  const validWarehouses = ['Kho cơ 1A', 'Kho điện 1A', 'Kho cơ điện 1C'];
  const validPlants = ['Nhà máy 1A', 'Nhà máy 1B', 'Nhà máy 1C', 'Nhà QLVH'];

  const rawSource =
    row.kho_nguon || row.Kho_nguon || row.warehouse_source || row.warehouseSource || '';
  const rawTarget =
    row.kho_dich || row.Kho_dich || row.warehouse_target || row.warehouseTarget || '';

  let warehouseSource: string | undefined;
  let warehouseTarget: string | undefined;

  if (type === 'Nhập kho') {
    warehouseSource = deliverer;
    warehouseTarget = validWarehouses.includes(rawTarget) ? rawTarget : 'Kho cơ 1A';
  } else if (type === 'Xuất kho') {
    warehouseSource = validWarehouses.includes(rawSource) ? rawSource : 'Kho cơ 1A';
    warehouseTarget = validPlants.includes(rawTarget) ? rawTarget : 'Nhà máy 1A';
  } else {
    warehouseSource = validWarehouses.includes(rawSource) ? rawSource : 'Kho cơ 1A';
    warehouseTarget = validWarehouses.includes(rawTarget) ? rawTarget : 'Kho điện 1A';
  }

  return {
    id: String(row.id || row.ma_phieu || row.code || Math.random()),
    code: row.ma_phieu || row.Ma_phieu || row.code || row.Code || 'PN-CHUA-CO-MA',
    type,
    deliverer,
    receiver: type === 'Nhập kho' ? undefined : receiver,
    warehouseSource,
    warehouseTarget,
    createdAt:
      row.thoi_gian ||
      row.Thoi_gian ||
      row.ngay_tao ||
      row.created_at ||
      row.createdAt ||
      new Date().toLocaleString('vi-VN'),
    creator,
    approver: 'Đinh Bạt Quân',
    totalItems: Number(row.so_luong_mat_hang ?? row.total_items ?? row.totalItems ?? 1),
    status: row.trang_thai || row.Trang_thai || row.status || row.Status || 'Chờ duyệt',
    note: row.mo_ta || row.Mo_ta || row.ghi_chu || row.note || row.Note || '',
  };
}

/**
 * Fetch all records from table "Phieu_kho" in Supabase
 */
export async function fetchPhieuKhoFromSupabase(): Promise<{
  data: StockSlip[] | null;
  error: string | null;
}> {
  const supabase = getSupabaseClient();
  if (!supabase) {
    return { data: null, error: 'Chưa cấu hình Supabase URL hoặc Anon Key' };
  }

  try {
    // Supabase table name can be 'Phieu_kho' or 'phieu_kho'
    let result = await supabase.from('Phieu_kho').select('*').order('id', { ascending: false });

    // Fallback if case sensitive 'phieu_kho'
    if (result.error && result.error.code === '42P01') {
      result = await supabase.from('phieu_kho').select('*').order('id', { ascending: false });
    }

    if (result.error) {
      return { data: null, error: result.error.message };
    }

    const slips: StockSlip[] = (result.data || []).map(mapRowToStockSlip);
    return { data: slips, error: null };
  } catch (err: any) {
    return { data: null, error: err.message || 'Lỗi kết nối bảng Phieu_kho' };
  }
}

/**
 * Insert a new slip into table "Phieu_kho" in Supabase
 */
export async function insertPhieuKhoToSupabase(slip: {
  code: string;
  type: string;
  createdAt: string;
  creator: string;
  note?: string;
  status: string;
  warehouseSource?: string;
  warehouseTarget?: string;
  approver?: string;
  totalItems?: number;
}): Promise<{ success: boolean; error: string | null }> {
  const supabase = getSupabaseClient();
  if (!supabase) {
    return { success: false, error: 'Chưa cấu hình Supabase URL hoặc Anon Key' };
  }

  // Payload with both common naming conventions
  const payloadVi = {
    ma_phieu: slip.code,
    loai_phieu: slip.type,
    thoi_gian: slip.createdAt,
    nguoi_tao: slip.creator,
    mo_ta: slip.note || '',
    trang_thai: slip.status,
    kho_nguon: slip.warehouseSource || null,
    kho_dich: slip.warehouseTarget || null,
    nguoi_duyet: slip.approver || 'Chờ duyệt',
    so_luong_mat_hang: slip.totalItems || 1,
  };

  const payloadEn = {
    code: slip.code,
    type: slip.type,
    created_at: slip.createdAt,
    creator: slip.creator,
    note: slip.note || '',
    status: slip.status,
    warehouse_source: slip.warehouseSource || null,
    warehouse_target: slip.warehouseTarget || null,
    approver: slip.approver || 'Chờ duyệt',
    total_items: slip.totalItems || 1,
  };

  try {
    // Try table "Phieu_kho" with Vietnamese fields first
    let res = await supabase.from('Phieu_kho').insert([payloadVi]);

    // If schema mismatch (column doesn't exist), try English fields
    if (res.error && res.error.message.includes('column')) {
      res = await supabase.from('Phieu_kho').insert([payloadEn]);
    }

    // If table name case insensitive issue
    if (res.error && res.error.code === '42P01') {
      res = await supabase.from('phieu_kho').insert([payloadVi]);
      if (res.error && res.error.message.includes('column')) {
        res = await supabase.from('phieu_kho').insert([payloadEn]);
      }
    }

    if (res.error) {
      return { success: false, error: res.error.message };
    }

    return { success: true, error: null };
  } catch (err: any) {
    return { success: false, error: err.message || 'Lỗi khi lưu vào Phieu_kho' };
  }
}
