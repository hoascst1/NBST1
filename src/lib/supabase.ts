import { createClient, SupabaseClient } from '@supabase/supabase-js';
import { StockSlip } from '../types/warehouse';

/**
 * Helper to check if a string is a valid HTTP or HTTPS URL for Supabase
 */
export const isValidSupabaseUrl = (urlStr: string): boolean => {
  if (!urlStr || typeof urlStr !== 'string') return false;
  const trimmed = urlStr.trim();
  if (
    trimmed.includes('your-project.supabase.co') ||
    trimmed.includes('MY_SUPABASE_URL') ||
    trimmed.length < 10
  ) {
    return false;
  }
  try {
    const parsed = new URL(trimmed);
    return (parsed.protocol === 'http:' || parsed.protocol === 'https:') && parsed.hostname.length > 3;
  } catch {
    return false;
  }
};

/**
 * Normalizes URL (adding https:// if user only pasted hostname)
 */
export const normalizeSupabaseUrl = (rawUrl: string): string => {
  let url = (rawUrl || '').trim();
  if (!url) return '';
  if (!url.startsWith('http://') && !url.startsWith('https://')) {
    url = `https://${url}`;
  }
  return url;
};

// Read from Vite environment variables or localStorage fallback
const getSupabaseConfig = () => {
  const envUrl = normalizeSupabaseUrl(import.meta.env.VITE_SUPABASE_URL || '');
  const envKey = (import.meta.env.VITE_SUPABASE_ANON_KEY || '').trim();

  const rawLocalUrl = typeof window !== 'undefined' ? localStorage.getItem('ST1_SUPABASE_URL') || '' : '';
  const localUrl = normalizeSupabaseUrl(rawLocalUrl);
  const localKey = (typeof window !== 'undefined' ? localStorage.getItem('ST1_SUPABASE_ANON_KEY') || '' : '').trim();

  let url = '';
  if (isValidSupabaseUrl(envUrl)) {
    url = envUrl;
  } else if (isValidSupabaseUrl(localUrl)) {
    url = localUrl;
  }

  let key = '';
  if (envKey && envKey !== 'your-anon-key' && envKey.length > 10) {
    key = envKey;
  } else if (localKey && localKey !== 'your-anon-key' && localKey.length > 10) {
    key = localKey;
  }

  return { url, key };
};

let cachedClient: SupabaseClient | null = null;
let lastUsedUrl = '';
let lastUsedKey = '';

export const isSupabaseConfigured = (): boolean => {
  const { url, key } = getSupabaseConfig();
  return isValidSupabaseUrl(url) && Boolean(key && key.length >= 15);
};

export const getSupabaseClient = (): SupabaseClient | null => {
  if (!isSupabaseConfigured()) return null;

  const { url, key } = getSupabaseConfig();

  if (cachedClient && lastUsedUrl === url && lastUsedKey === key) {
    return cachedClient;
  }

  try {
    cachedClient = createClient(url, key, {
      auth: {
        persistSession: true,
        autoRefreshToken: true,
      },
    });
    lastUsedUrl = url;
    lastUsedKey = key;
    return cachedClient;
  } catch (err) {
    console.warn('Supabase client initialization skipped:', err);
    return null;
  }
};

export const saveSupabaseConfig = (rawUrl: string, rawKey: string) => {
  if (typeof window !== 'undefined') {
    const normalizedUrl = normalizeSupabaseUrl(rawUrl);
    const trimmedKey = (rawKey || '').trim();

    if (isValidSupabaseUrl(normalizedUrl)) {
      localStorage.setItem('ST1_SUPABASE_URL', normalizedUrl);
    } else {
      localStorage.removeItem('ST1_SUPABASE_URL');
    }

    if (trimmedKey && trimmedKey.length > 10 && trimmedKey !== 'your-anon-key') {
      localStorage.setItem('ST1_SUPABASE_ANON_KEY', trimmedKey);
    } else {
      localStorage.removeItem('ST1_SUPABASE_ANON_KEY');
    }

    cachedClient = null; // Reset cache
    lastUsedUrl = '';
    lastUsedKey = '';
  }
};

export const clearSupabaseConfig = () => {
  if (typeof window !== 'undefined') {
    localStorage.removeItem('ST1_SUPABASE_URL');
    localStorage.removeItem('ST1_SUPABASE_ANON_KEY');
    cachedClient = null;
    lastUsedUrl = '';
    lastUsedKey = '';
  }
};

export const getCurrentSupabaseConfig = () => getSupabaseConfig();

